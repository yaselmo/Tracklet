class Command(BaseCommand):
    """Create or refresh the public portfolio demo dataset."""

    help = 'Create an idempotent, entirely fictional Tracklet public-demo dataset'

    def add_arguments(self, parser):
        parser.add_argument(
            '--reset',
            action='store_true',
            help='Remove only objects created by this command before reseeding',
        )

    @transaction.atomic
    def handle(self, *args, **options):
        password = os.environ.get('TRACKLET_DEMO_PASSWORD', '')
        if not password:
            raise CommandError(
                'Set TRACKLET_DEMO_PASSWORD to a clearly fake, changeable demo password.'
            )

        if options['reset']:
            self._remove_demo_data()

        user = self._create_demo_user(password)
        part_categories, stock_categories = self._create_categories()
        locations = self._create_locations()
        companies = self._create_companies()
        parts, stock_items = self._create_inventory(
            part_categories, stock_categories, locations
        )
        calibration_counts = self._create_calibration_data(parts, part_categories)
        events, assignments = self._create_events(parts)
        rentals, rental_lines = self._create_rentals(stock_items, companies, user)

        # Recalculate canonical availability only after reservations exist.
        for item in stock_items.values():
            if item.status in [
                StockStatus.LOST.value,
                StockStatus.DAMAGED.value,
                StockStatus.DESTROYED.value,
                StockStatus.REJECTED.value,
            ]:
                availability = item.infer_availability()
            elif item.serial in {'DEMO-PWR-001', 'DEMO-PWR-002'}:
                availability = StockItem.Availability.UNAVAILABLE
            else:
                availability = item.infer_availability()

            StockItem.objects.filter(pk=item.pk).update(availability=availability)

        counts = {
            'instruments': len(stock_items),
            'categories': len(stock_categories),
            'locations': StockLocation.objects.filter(
                name__in=[DEMO_LOCATION_ROOT, *LOCATIONS]
            ).count(),
            'events': len(events),
            'reservations': len(assignments),
            'rentals': len(rentals),
            'rental lines': len(rental_lines),
        }
        summary = ', '.join(f'{key}={value}' for key, value in counts.items())
        calibration = ', '.join(
            f'{key}={value}' for key, value in calibration_counts.items()
        )
        self.stdout.write(self.style.SUCCESS(f'Demo seed complete: {summary}'))
        self.stdout.write(f'Calibration parameters: {calibration}')
        self.stdout.write(
            'Demo account: demo (non-staff, non-superuser, view-only roles)'
        )

    def _remove_demo_data(self):
        RentalOrder.objects.filter(reference__startswith='DEMO-RN-').delete()
        Event.objects.filter(reference__startswith='DEMO-EV-').delete()
        StockItem.objects.filter(serial__startswith='DEMO-').delete()
        Part.objects.filter(IPN__startswith='DEMO-').delete()

        for name in reversed(LOCATIONS):
            StockLocation.objects.filter(
                name=name, parent__name=DEMO_LOCATION_ROOT
            ).delete()
        StockLocation.objects.filter(name=DEMO_LOCATION_ROOT).delete()

        for name in CATEGORIES:
            PartCategory.objects.filter(
                name=name, parent__name='Demo Equipment'
            ).delete()
            StockCategory.objects.filter(name=name).delete()
        PartCategory.objects.filter(name='Demo Equipment').delete()

        Company.objects.filter(name__in=[*MANUFACTURERS, *CUSTOMERS]).delete()
        Planner.objects.filter(name='Demo Operations Team').delete()
        Venue.objects.filter(
            name__in=['Demo North Basin', 'Demo Hydraulics Hall', 'Demo Coastal Annex']
        ).delete()
        EventType.objects.filter(
            name__in=['Demo Field Study', 'Demo Lab Test', 'Demo Validation']
        ).delete()
        ParameterTemplate.objects.filter(metadata__tracklet_demo=True).delete()
        User.objects.filter(username='demo').delete()
        Group.objects.filter(name=DEMO_GROUP).delete()

    def _create_demo_user(self, password):
        group, _ = Group.objects.get_or_create(name=DEMO_GROUP)
        update_group_roles(group)

        view_roles = {
            RuleSetEnum.PART_CATEGORY,
            RuleSetEnum.PART,
            RuleSetEnum.STOCK_LOCATION,
            RuleSetEnum.STOCK,
            RuleSetEnum.SALES_ORDER,
        }
        for ruleset in RuleSet.objects.filter(group=group):
            ruleset.can_view = ruleset.name in view_roles
            ruleset.can_add = False
            ruleset.can_change = False
            ruleset.can_delete = False
            ruleset.save()
        update_group_roles(group)

        user, _ = User.objects.update_or_create(
            username='demo',
            defaults={
                'first_name': 'Demo',
                'last_name': 'Visitor',
                'email': 'demo@example.invalid',
                'is_active': True,
                'is_staff': False,
                'is_superuser': False,
            },
        )
        user.groups.set([group])
        user.set_password(password)
        user.save()
        return user

