    def _create_inventory(self, part_categories, stock_categories, locations):
        parts = {}
        stock_items = {}

        repair_serials = {'DEMO-PWR-001', 'DEMO-PWR-002'}
        missing_serials = {'DEMO-PWR-003'}
        broken_serials = {'DEMO-FE-001', 'DEMO-FE-002'}
        found_serials = {'DEMO-FE-003'}

        for category, manufacturer, name, suffix, location in INVENTORY:
            serial = f'DEMO-{suffix}'
            part, _ = Part.objects.update_or_create(
                IPN=serial,
                revision=None,
                defaults={
                    'name': name,
                    'description': f'{manufacturer} fictional demo instrument',
                    'keywords': f'demo, equipment, {category}, {manufacturer}',
                    'category': part_categories[category],
                    'default_location': locations[location],
                    'trackable': True,
                    'testable': category
                    not in {'Cables / Accessories', 'Power Equipment'},
                    'purchaseable': False,
                    'salable': False,
                    'active': True,
                    'metadata': {
                        'tracklet_demo': True,
                        'fictional_manufacturer': manufacturer,
                    },
                },
            )
            parts[serial] = part

            status = StockStatus.OK.value
            availability = StockItem.Availability.AVAILABLE
            notes = DEMO_MARKER
            if serial in repair_serials:
                status = StockStatus.ATTENTION.value
                availability = StockItem.Availability.UNAVAILABLE
                notes = f'Queued for fictional workshop inspection. {DEMO_MARKER}'
            elif serial in missing_serials:
                status = StockStatus.LOST.value
                availability = StockItem.Availability.MISSING
                notes = (
                    f'Marked missing during a fictional demo stocktake. {DEMO_MARKER}'
                )
            elif serial in broken_serials:
                status = StockStatus.DAMAGED.value
                availability = StockItem.Availability.BROKEN
                notes = f'Removed from service in the fictional demo. {DEMO_MARKER}'
            elif serial in found_serials:
                status = StockStatus.RETURNED.value
                notes = f'Recently found and returned to storage. {DEMO_MARKER}'

            item, _ = StockItem.objects.update_or_create(
                part=part,
                serial=serial,
                defaults={
                    'title': name,
                    'location': locations[location],
                    'category': stock_categories[category],
                    'quantity': 1,
                    'status': status,
                    'availability': availability,
                    'notes': notes,
                    'metadata': {'tracklet_demo': True},
                },
            )
            stock_items[serial] = item

        return parts, stock_items

    def _create_calibration_data(self, parts, part_categories):
        content_type = ContentType.objects.get_for_model(Part)
        templates = {}
        template_specs = {
            'required': ('Calibration Required', '', True),
            'interval': ('Calibration Interval', 'days', False),
            'last': ('Calibration Last Completed', '', False),
            'due': ('Calibration Next Due', '', False),
        }
        for key, (name, units, checkbox) in template_specs.items():
            templates[key], _ = ParameterTemplate.objects.update_or_create(
                name=name,
                defaults={
                    'model_type': content_type,
                    'description': f'Fictional public-demo calibration field. {DEMO_MARKER}',
                    'units': units,
                    'checkbox': checkbox,
                    'enabled': True,
                    'metadata': {'tracklet_demo': True},
                },
            )

        calibrated_categories = {
            'Pressure Sensors',
            'Temperature Sensors',
            'Flow Sensors',
            'Data Acquisition',
            'Measurement Equipment',
            'Field Equipment',
        }
        for name, category in part_categories.items():
            required = name in calibrated_categories
            PartCategoryParameterTemplate.objects.update_or_create(
                category=category,
                template=templates['required'],
                defaults={'default_value': str(required)},
            )
            if required:
                PartCategoryParameterTemplate.objects.update_or_create(
                    category=category,
                    template=templates['interval'],
                    defaults={'default_value': '365'},
                )

        today = date.today()
        counts = {'healthy': 0, 'due_soon': 0, 'overdue': 0, 'not_required': 0}
        required_index = 0
        for _serial, part in parts.items():
            category = part.category.name
            required = category in calibrated_categories
            values = {'required': str(required)}
            if required:
                state = ['healthy', 'due_soon', 'overdue'][required_index % 3]
                required_index += 1
                if state == 'healthy':
                    last, due = today - timedelta(days=45), today + timedelta(days=320)
                elif state == 'due_soon':
                    last, due = today - timedelta(days=350), today + timedelta(days=15)
                else:
                    last, due = today - timedelta(days=390), today - timedelta(days=25)
                values.update({
                    'interval': '365',
                    'last': last.isoformat(),
                    'due': due.isoformat(),
                })
                counts[state] += 1
            else:
                counts['not_required'] += 1

            for key, value in values.items():
                Parameter.objects.update_or_create(
                    model_type=content_type,
                    model_id=part.pk,
                    template=templates[key],
                    defaults={
                        'data': value,
                        'note': DEMO_MARKER,
                        'metadata': {'tracklet_demo': True},
                    },
                )
        return counts

